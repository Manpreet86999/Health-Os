// Rasterize the user's SVG source; keep all app/report derivatives reproducible.
import { readFile, writeFile, copyFile, access } from 'node:fs/promises';
import path from 'node:path';
import puppeteer from 'puppeteer';
const root=path.resolve(import.meta.dirname,'..'),publicRoot=path.join(root,'src/client/public');
const source=await readFile(path.join(publicRoot,'health-os-logo.svg'),'utf8');
const mark=source.replace(/<text\b[\s\S]*?<\/text>/g,'');
await writeFile(path.join(publicRoot,'health-os-mark.svg'),mark);
await copyFile(path.join(publicRoot,'health-os-logo.svg'),path.join(publicRoot,'body-os-logo.svg'));
const candidates=[process.env.BRAND_BROWSER,`${process.env['PROGRAMFILES(X86)']}/Microsoft/Edge/Application/msedge.exe`,`${process.env.PROGRAMFILES}/Microsoft/Edge/Application/msedge.exe`].filter(Boolean);
let executablePath;for(const candidate of candidates){try{await access(candidate);executablePath=candidate;break;}catch{}}
const browser=await puppeteer.launch({headless:true,...(executablePath?{executablePath}:{})});
try{
 const page=await browser.newPage();
 const render=async(svg,size)=>{await page.setViewport({width:size,height:size,deviceScaleFactor:1});await page.setContent(`<style>html,body{margin:0;background:transparent}svg{display:block;width:100vw;height:100vh}</style>${svg}`);return Buffer.from(await page.screenshot({type:'png',omitBackground:true}));};
 for(const size of [192,512]){
  const png=await render(source,size);
  for(const name of [`health-os-${size}.png`,`icon-${size}.png`,`body-os-app-${size}-v5.png`,`body-os-app-${size}-v2.png`])await writeFile(path.join(publicRoot,name),png);
 }
 const report=await render(mark,192);
 await writeFile(path.join(publicRoot,'health-os-report.png'),report);
 for(const name of ['body-os-logo.png','body-os-logo-v5.png'])await writeFile(path.join(publicRoot,name),report);
 await writeFile(path.join(root,'src/shared/report-logo.ts'),`// Generated by scripts/generate-brand-assets.mjs from the supplied Health OS SVG.\nexport const REPORT_LOGO_DATA_URI = 'data:image/png;base64,${report.toString('base64')}';\n`);
 const emailPath=path.join(root,'src/shared/report-email-assets.js');
 const email=await readFile(emailPath,'utf8');
 const updated=email.replace(/("brand"\s*:\s*")[^"]*(")/,`$1${report.toString('base64')}$2`);
 if(updated===email)throw Error('Email brand asset was not found.');
 await writeFile(emailPath,updated);
 const iconPng=await render(mark,64),ico=Buffer.alloc(22);
 ico.writeUInt16LE(1,2);ico.writeUInt16LE(1,4);ico[6]=64;ico[7]=64;ico.writeUInt16LE(1,10);ico.writeUInt16LE(32,12);ico.writeUInt32LE(iconPng.length,14);ico.writeUInt32LE(22,18);
 await writeFile(path.join(publicRoot,'favicon.ico'),Buffer.concat([ico,iconPng]));
 console.log('Generated web, report and Windows icon assets from Health OS source SVG.');
}finally{await browser.close();}
